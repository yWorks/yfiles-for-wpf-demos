using System;
using System.Linq;
using System.Windows;
using System.Windows.Threading;
using yWorks.Analysis;
using yWorks.Controls;
using yWorks.Controls.Input;
using yWorks.Geometry;
using yWorks.Graph;
using yWorks.Layout;
using yWorks.Layout.Orthogonal;

namespace yWorks.Demo.AbortHandler
{
  /// <summary>
  ///   Shows how to use an <see cref="yWorks.Layout.Graph.LayoutAbortController"/> to stop or cancel running layout
  ///   algorithms.
  /// </summary>
  /// <remarks>
  ///   This demo uses a <see cref="yWorks.Graph.LayoutExtensions.ApplyLayoutAnimated"/> method to run the layout in a
  ///   background thread and register the <see cref="yWorks.Layout.Graph.LayoutAbortController"/> which both are
  ///   prerequisites to abort a running layout algorithm.
  /// </remarks>
  [Demo("abort-handler", "layout", "Abort Handler", Summary = "Shows how to abort running layout algorithms.",
      Tags = ["layout", "abort"], Keywords = ["LayoutAbortController", "cancellation", "background layout"],
      RelatedDemos = [])]
  public partial class AbortHandlerDemo
  {
    private bool layoutRunning;

    /// <summary>
    ///   Automatically generated by Visual Studio.
    ///   Wires up the UI components and adds a
    ///   <see cref="GraphControl"/> to the form.
    /// </summary>
    public AbortHandlerDemo() {
      InitializeComponent();
    }

    /// <summary>
    ///   Initializes this demo.
    /// </summary>
    /// <seealso cref="InitializeGraph"/>
    protected virtual void OnLoaded(object source, EventArgs e) {
      // initialize the graph
      InitializeGraph();

      // initialize an input mode
      GraphControl.InputMode = new GraphEditorInputMode();

      GraphControl.FitGraphBounds();
    }

    /// <summary>
    ///   Initializes the graph instance setting default styles
    ///   and creating a sample graph.
    /// </summary>
    protected virtual void InitializeGraph() {
      // set the default node style and size
      DemoStyles.InitDemoStyles(GraphControl.Graph);
      GraphControl.Graph.NodeDefaults.Size = new SizeD(60, 40);

      BuildGraph(GraphControl.Graph);

      // Enable undo support
      GraphControl.Graph.SetUndoEngineEnabled(true);
    }

    /// <summary>
    ///   Creates a large random graph to give the layout algorithms something to chew.
    /// </summary>
    private static void BuildGraph(IGraph graph) {
      graph.Clear();

      // Create lots of nodes
      var nodes = new INode[500];
      for (var i = 0; i < nodes.Length; i++) {
        nodes[i] = graph.CreateNode();
      }
      // Connect the nodes randomly
      var random = new Random(0);
      for (var i = 0; i < nodes.Length; i++) {
        int edgeCount;
        if (random.Next(10) == 0) {
          edgeCount = 4 + random.Next(5);
        } else {
          edgeCount = random.Next(3);
        }
        for (var j = 0; j < edgeCount; j++) {
          graph.CreateEdge(nodes[i], nodes[random.Next(nodes.Length)]);
        }
      }

      // remove all components except the largest one
      var adapter = new StructureGraphAdapter(graph);
      var components = LayoutGraphAlgorithms.ConnectedComponents(adapter.StructureGraph).ToArray();

      Array.Sort(components, (o1, o2) => o2.Count() - o1.Count());

      for (var i = components.Length - 1; i > 0; i--) {
        foreach (var node in components[i]) {
          graph.Remove(adapter.GetOriginalNode(node)!);
        }
      }

      // add labels
      var count = 0;
      foreach (var node in graph.Nodes) {
        graph.AddLabel(node, count++.ToString());
      }
      RandomizeGraph(graph);
    }

    /// <summary>
    ///   Gets the <see cref="GraphControl"/> of this demo.
    /// </summary>
    public GraphControl GraphControl => graphControl;

    private static void RandomizeGraph(IGraph graph) {
      // Remove all bends
      var bends = graph.Edges.SelectMany(e => e.Bends).ToList();
      foreach (var bend in bends) {
        graph.Remove(bend);
      }
      var r = new Random();
      // Place nodes in random locations
      foreach (var node in graph.Nodes) {
        graph.SetNodeCenter(node, new PointD(r.Next(1500), r.Next(1500)));
      }
    }

    /// <summary>
    ///   Runs a new layout after the layout button was clicked.
    /// </summary>
    private async void OnLayoutButtonClicked(object sender, RoutedEventArgs e) {
      // avoid concurrent layouts
      if (layoutRunning) {
        return;
      }
      layoutRunning = true;

      // create a new layout algorithm
      // OrthogonalLayout is used here because it is one of the more expensive layout algorithms in the yFiles library,
      // i.e. OrthogonalLayout will take a long time (like tens of seconds) to calculate a layout for the sample graph
      // however, stopping/cancelling layout algorithms with LayoutAbortController works with all layout algorithms
      // not just OrthogonalLayout
      var layout = new OrthogonalLayout();

      // create an executor to start the layout
      var layoutExecutor = new LayoutExecutor(graphControl, layout) { AnimationDuration = TimeSpan.FromSeconds(1) };

      // use the LayoutAbortController instance offered by the created executor
      var abortController = layoutExecutor.LayoutAbortController;

      // set up the LayoutAbortController and the AbortDialog
      double stopDurationSeconds;
      if (double.TryParse(stopDuration.Text.Trim(), out stopDurationSeconds) && stopDurationSeconds >= 0) {
        abortController.StopDuration = TimeSpan.FromSeconds(stopDurationSeconds);
      }

      double cancelDurationSeconds;
      if (double.TryParse(cancelDuration.Text.Trim(), out cancelDurationSeconds) && cancelDurationSeconds >= 0) {
        abortController.CancelDuration = TimeSpan.FromSeconds(cancelDurationSeconds);
      }

      var abortDialog = new AbortDialog {
          LayoutAbortController = abortController,
          Owner = Window.GetWindow(this)
      };

      // see if we are doing a quick layout - and if it takes more than a few seconds, we open the dialog to
      // enable the user to stop or cancel the execution
      var showDialogTimer =
          new DispatcherTimer(DispatcherPriority.Normal, Dispatcher) { Interval = TimeSpan.FromSeconds(2) };

      showDialogTimer.Tick += delegate {
        // it could be that the layout is already done or already cancelled by the timer - so check whether we still
        // need to open the dialog
        if (layoutRunning && abortController.TimeToCancel() > TimeSpan.Zero) {
          // open the abort dialog
          abortDialog.Show();
        }
        // we only want to let it go off once - so stop the timer
        showDialogTimer.Stop();
      };

      // kick-off the timer
      showDialogTimer.Start();

      // start the layout
      try {
        await layoutExecutor.Start();
      } catch (OperationCanceledException) {
        // Layout has been canceled
      }

      // after the layout has been finished (or aborted): close the dialog
      if (abortDialog.IsVisible) {
        abortDialog.Close();
      }
      layoutRunning = false;
    }

    [STAThread]
    private static void Main() => Run<AbortHandlerDemo>();
  }
}
