    /// <summary>
    ///   Does the label placement using the generic labeling algorithm. Before this, the model and size of the labels is
    ///   set according to the option handlers settings.
    /// </summary>
    private async Task DoLabelPlacement() {
      if (inLayout) {
        return;
      }
      inLayout = true;

      toolBar.IsEnabled = false;
      editorControl.IsEnabled = false;

      // desired label model
      var labelModelParameter = LabelModels[(string) Handler[LABEL_MODEL].Value];
      var size = (int) Handler[LABEL_SIZE].Value;

      foreach (var label in graphControl.Graph.Labels) {
        if (label.Owner is INode) {
          // only update the label model parameter if the label model changed
          if (labelModelParameter.Model != graphControl.Graph.NodeDefaults.Labels.LayoutParameter.Model) {
            graphControl.Graph.SetLabelLayoutParameter(label, labelModelParameter);
          }
          var cityLabelStyle = label.Style as CityLabelStyle;
          if (cityLabelStyle != null && cityLabelStyle.InnerLabelStyle is LabelStyle) {
            ((LabelStyle) cityLabelStyle.InnerLabelStyle).TextSize = size;
          }
          graphControl.Graph.AdjustLabelPreferredSize(label);
        }
      }
      {
        // set as default label model parameter
        graphControl.Graph.NodeDefaults.Labels.LayoutParameter = labelModelParameter;
        var cityLabelStyle = graphControl.Graph.NodeDefaults.Labels.Style as CityLabelStyle;
        if (cityLabelStyle != null && cityLabelStyle.InnerLabelStyle is LabelStyle) {
          ((LabelStyle) cityLabelStyle.InnerLabelStyle).TextSize = size;
        }
      }
      graphControl.Invalidate();

      // configure and run the layout algorithm
      var labelingAlgorithm = new GenericLabeling {
          StopDuration = TimeSpan.Zero, Scope = LabelingScope.NodeLabels, ReduceLabelOverlaps = true
      };

      var labelingData = labelingAlgorithm.CreateLayoutData(graphControl.Graph);
      labelingData.NodeLabelCandidateProcessors.Constant = NodeLabelWeightDelegate;
      labelingData.EdgeLabelCandidateProcessors.Constant = EdgeLabelWeightDelegate;

      var layoutExecutor = new LayoutExecutor(graphControl, graphControl.Graph, labelingAlgorithm) {
          LayoutData = labelingData, AnimationDuration = TimeSpan.FromMilliseconds(500), AnimateViewport = false
      };

      await layoutExecutor.Start();

      toolBar.IsEnabled = true;
      editorControl.IsEnabled = true;
      inLayout = false;
    }

    private const double CustomWeightRatio = 0.1;

    private void NodeLabelWeightDelegate(IEnumerable<LabelCandidate> candidates, NodeLabel label) {
      foreach (var candidate in candidates) {
        if (candidate is ExtendedNodeLabelCandidate extendedCandidate) {
          var customWeight = GetCustomWeight(extendedCandidate);
          extendedCandidate.Weight = (1 - CustomWeightRatio) * extendedCandidate.Weight +
              (CustomWeightRatio * customWeight);
        } else {
          candidate.Weight *= 1 - CustomWeightRatio;
        }
      }
    }

    private double GetCustomWeight(ExtendedNodeLabelCandidate candidate) {
      // depending on the label models, custom weights could be calculated here
      return 1.0;
    }

    private static void EdgeLabelWeightDelegate(IEnumerable<LabelCandidate> candidates, EdgeLabel label) {
      foreach (var candidate in candidates) {
        candidate.Weight *= 1 - CustomWeightRatio;
      }
    }

    #region option handler

    private void SetupOptions() {
      SetupHandler();
      // create the options
      // populate the control to visualize them
      editorControl.OptionHandler = Handler;
      editorControl.IsAutoAdopt = true;
      editorControl.IsAutoCommit = true;
    }


    /// <summary>
    ///   Initializes the option handler for the export
    /// </summary>
    private void SetupHandler() {
      Handler = new OptionHandler(NODE_LABELING);
      OptionGroup currentGroup = Handler;

      // Trigger an automatic relayout whenever an option changes
      currentGroup.AddList(LABEL_MODEL, LabelModels.Keys, "LABEL_MODEL_EXTERIOR").PropertyChanged +=
          HandlerPropertyChanged;
      currentGroup.AddInt(LABEL_SIZE, 8).PropertyChanged += HandlerPropertyChanged;

      // localization
      var rm = new ResourceManager("Demo.yFiles.Layout.NodeLabeling.NodeLabeling", Assembly.GetExecutingAssembly());
      var rmf = new ResourceManagerI18NFactory();
      rmf.AddResourceManager(Handler.Name, rm);
      Handler.I18nFactory = rmf;
    }

    private async void HandlerPropertyChanged(object sender, PropertyChangedEventArgs e) {
      await DoLabelPlacement();
    }

