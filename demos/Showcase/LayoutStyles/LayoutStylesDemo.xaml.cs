    private static void PrevComboboxItem(ComboBox comboBox) {
      if (comboBox.SelectedIndex <= 0) {
        return;
      }
      // make sure you can not get into invalid state
      var newIndex = comboBox.SelectedIndex;
      do {
        newIndex--;
      } while (comboBox.Items[newIndex] is Separator);
      comboBox.SelectedIndex = newIndex;
    }

    private static void NextComboboxItem(ComboBox comboBox) {
      if (comboBox.SelectedIndex >= comboBox.Items.Count - 1) {
        return;
      }
      // make sure you can not get into invalid state
      var newIndex = comboBox.SelectedIndex;
      do {
        newIndex++;
      } while (comboBox.Items[newIndex] is Separator);
      comboBox.SelectedIndex = newIndex;
    }

