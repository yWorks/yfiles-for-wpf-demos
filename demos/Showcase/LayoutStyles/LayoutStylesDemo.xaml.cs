    /// <summary>
    ///   Adds a custom "Sample Graph" entry for a graph modified by the user.
    /// </summary>
    private void AddCustomGraphEntry() {
      customGraphSelected = true;

      var hasCustomGraph = false;
      var samples = new List<SampleData>();
      foreach (var o in SampleComboBox.ItemsSource) {
        if (o is not SampleData sample) {
          continue;
        }

        samples.Add(sample);

        if (customGraphSample == sample) {
          hasCustomGraph = true;
        }
      }
      if (!hasCustomGraph) {
        samples.Add(customGraphSample);
      }

      SampleComboBox.SelectionChanged -= OnSampleChanged;
      SampleComboBox.ItemsSource = samples.ToArray();
      SampleComboBox.SelectedIndex = samples.Count - 1;
      SampleComboBox.SelectionChanged += OnSampleChanged;
    }

    /// <summary>
    ///   Loads the temporary stored modified graph into the main <see cref="GraphControl"/>.
    /// </summary>
    private void LoadModifiedGraph() {
      if (customGraph != null) {
        var graph = Graph;
        graph.Clear();
        new GraphCopier().Copy(customGraph, graph);
      }
    }

    /// <summary>
    ///   Copies the current graph into a temporary <see cref="IGraph"/> instance for later use.
    /// </summary>
    private void StoreModifiedGraph() {
      customGraph = new DefaultGraph();
      new GraphCopier().Copy(Graph, customGraph);
    }

    /// <summary>
    ///   Stores the current state as modified graph and adds a "Sample Graph" entry for it.
    /// </summary>
    private void UpdateModifiedGraphSample() {
      AddCustomGraphEntry();
      StoreModifiedGraph();
    }

