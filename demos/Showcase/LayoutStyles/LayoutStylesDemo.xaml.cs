    /// <summary>
    ///   Called when the current layout changes, updates UI and applies special settings
    /// </summary>
    private async void OnLayoutChanged(object sender, SelectionChangedEventArgs e) {
      if (LayoutComboBox.SelectedItem is not LayoutConfigurationData lcd) {
        return;
      }

      SampleComboBox.SelectionChanged -= OnSampleChanged;
      InitializeSamples(lcd);
      if (customGraphSelected) {
        UpdateLayoutConfiguration();
        Editor.Invalidate();
      } else {
        await OnSampleChangedCore();
      }
      SampleComboBox.SelectionChanged += OnSampleChanged;

      // maybe enable thickness buttons
      UpdateThicknessButtonsState(lcd.Name);

      await ApplyLayout(true);
    }

    private void InitializeSamples(LayoutConfigurationData lcd) {
      if (customGraphSelected || customGraph != null) {
        List<SampleData> samples = [
            .. lcd.Samples,
            customGraphSample
        ];
        SampleComboBox.ItemsSource = samples.ToArray();
        SampleComboBox.SelectedIndex = customGraphSelected ? samples.Count - 1 : 0;
      } else {
        SampleComboBox.ItemsSource = lcd.Samples;
        SampleComboBox.SelectedIndex = 0;
      }
    }

    private void UpdateThicknessButtonsState(string algorithm) {
      var enabled = "Hierarchical" == algorithm;
      GenerateRandomEdgeThicknessButton.IsEnabled = enabled;
      ResetAllEdgeThicknessButton.IsEnabled = enabled;
      GenerateRandomEdgeDirectionsButton.IsEnabled = enabled;
      ResetAllEdgeDirectionsButton.IsEnabled = enabled;

      if (!enabled) {
        ResetEdgeThickness();
        ResetEdgeDirectedness();
      }
    }

    /// <summary>
    ///   Actually applies the layout.
    /// </summary>
    /// <param name="clearUndo">A value determining whether to clear the Undo queue after layout.</param>
    private async Task ApplyLayout(bool clearUndo) {
      var data = (LayoutConfigurationData) LayoutComboBox.SelectedItem;
      var config = data.Configuration;
      SetUserInteractionState(false);
      await config.Apply(graphControl, () => { });
      SetUserInteractionState(true);
      CheckButtonStates(LayoutComboBox, PreviousLayoutButton, NextLayoutButton);
      if (clearUndo) {
        Graph.GetUndoEngine()!.Clear();
      }
    }

    private void SetUserInteractionState(bool state) {
      Array.ForEach(
          new Control[] {
              PreviousLayoutButton,
              NextLayoutButton,
              ApplyButton,
              ResetButton,
              SampleComboBox,
              LayoutComboBox,
              NewButton,
              OpenButton,
              SaveAsButton
          }, e => e.IsEnabled = state);
    }

    private static void CheckButtonStates(ComboBox comboBox, Button previousButton, Button nextButton) {
      var maxReached = comboBox.SelectedIndex == comboBox.Items.Count - 1;
      var minReached = comboBox.SelectedIndex == 0;
      nextButton.IsEnabled = true;
      previousButton.IsEnabled = true;
      if (maxReached) {
        nextButton.IsEnabled = false;
      } else if (minReached) {
        previousButton.IsEnabled = false;
      }
    }

    private async void OnSampleChanged(object sender, SelectionChangedEventArgs e) {
      await OnSampleChangedCore();
      await ApplyLayout(true);
    }

    private async Task OnSampleChangedCore() {
      if (SampleComboBox.SelectedItem is not SampleData sample) {
        return;
      }

      if (customGraphSelected) {
        StoreModifiedGraph();
      } else if (customGraphSample == sample) {
        LoadModifiedGraph();
        customGraphSelected = true;
        return;
      }

      customGraphSelected = false;

      UpdateLayoutConfiguration();
      Editor.Invalidate();

      var stream = LoadAssemblyResource($"{sample.FileName}.graphml");
      CreateSampleReader(graphControl).Read(Graph, stream);

      await graphControl.FitGraphBounds();
    }

    private void UpdateLayoutConfiguration() {
      ((SampleData) SampleComboBox.SelectedItem).UpdateConfiguration(
          ((LayoutConfigurationData) LayoutComboBox.SelectedItem).Configuration);
    }

    private static GraphMLIOHandler CreateSampleReader(GraphControl graphControl) {
      var selectedEdges = new DictionaryMapper<IEdge, bool>();
      var selectedNodes = new DictionaryMapper<INode, bool>();

      var reader = new GraphMLIOHandler();
      reader.ClearGraphBeforeRead = true;
      reader.AddInputMapper("SelectedEdges", selectedEdges);
      reader.AddInputMapper("SelectedNodes", selectedNodes);
      reader.Parsing += (_, _) => {
        selectedEdges.Clear();
        selectedNodes.Clear();
      };
      reader.Parsed += (_, args) => {
        var selection = graphControl.Selection;
        selection.Clear();

        var graph = args.Context.Graph;
        foreach (var node in graph.Nodes) {
          if (selectedNodes[node]) {
            selection.Add(node);
          }
        }
        foreach (var edge in graph.Edges) {
          if (selectedEdges[edge]) {
            selection.Add(edge);
          }
        }
      };
      return reader;
    }

    /// <summary>
    ///   Creates the default input mode for the GraphControl, a <see cref="GraphEditorInputMode"/>.
    /// </summary>
    /// <returns>a new GraphEditorInputMode instance with added event listeners and demo-specific settings such as no labels</returns>
    protected virtual IInputMode CreateEditorInputMode() {
      // create default interaction with snapping and orthogonal edge editing
      var mode = new GraphEditorInputMode {
          SnapContext = new GraphSnapContext {
              Enabled = false,
              GridSnapType = GridSnapTypes.None
          },
          OrthogonalEdgeEditingContext = new OrthogonalEdgeEditingContext { Enabled = false },
          NavigationInputMode = {
              AllowCollapseGroup = false,
              AllowExpandGroup = false
          }
      };

      mode.KeyboardInputMode.AddCommandBinding(ApplicationCommands.New,
          (sender, _) => ((GraphControl) sender).Graph.Clear());

      // make bend creation more important than moving of selected edges
      // this has the effect that dragging a selected edge (not its bends)
      // will create a new bend instead of moving all bends
      // This is especially nicer in conjunction with orthogonal
      // edge editing because this creates additional bends every time
      // the edge is moved otherwise
      mode.CreateBendInputMode.Priority = mode.MoveSelectedItemsInputMode.Priority - 1;

      // also we add a context menu
      InitializeContextMenu(mode);

      // set the input mode
      graphControl.InputMode = mode;

      return mode;
    }

    private void InitializeContextMenu(GraphEditorInputMode mode) {
      mode.PopulateItemContextMenu += (_, args) => {
        args.Menu.Items.Clear();
        var hitNode = args.Item as INode;
        var hitEdge = args.Item as IEdge;
        var selection = GraphEditorInputMode.GraphSelection!;
        if (hitNode != null) {
          var selectNodeMenu = new MenuItem { Header = "Select All Nodes" };
          selectNodeMenu.Click += delegate {
            selection.Clear();
            foreach (var node in Graph.Nodes) {
              selection.Add(node);
            }
          };
          args.Menu.Items.Add(selectNodeMenu);
        } else if (hitEdge != null) {
          var selectEdgeMenu = new MenuItem { Header = "Select All Edges" };
          selectEdgeMenu.Click += delegate {
            selection.Clear();
            foreach (var edge in Graph.Edges) {
              selection.Add(edge);
            }
          };
          args.Menu.Items.Add(selectEdgeMenu);
        } else {
          args.Menu.Items.Add(new MenuItem {
              Command = ApplicationCommands.SelectAll,
              CommandTarget = graphControl
          });
        }
        // if one or more nodes are selected: add options to cut and copy
        if (selection.Nodes.Count > 0) {
          args.Menu.Items.Add(new MenuItem {
              Command = ApplicationCommands.Copy,
              CommandTarget = graphControl
          });
          args.Menu.Items.Add(new MenuItem {
              Command = ApplicationCommands.Cut,
              CommandTarget = graphControl
          });
        }
        if (!graphControl.Clipboard.IsEmpty) {
          args.Menu.Items.Add(new MenuItem {
              Command = ApplicationCommands.Paste,
              CommandTarget = graphControl
          });
        }
        // finally, if the context menu has at least one entry, set the showMenu flag
        if (args.Menu.Items.Count > 0) {
          args.ShowMenu = true;
        }
      };
    }

