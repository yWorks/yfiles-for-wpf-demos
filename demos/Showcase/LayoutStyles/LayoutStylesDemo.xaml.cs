    private void GenerateRandomEdgeThicknessImpl() {
      foreach (var edge in Graph.Edges) {
        var thickness = random.NextDouble() * 4 + 1;
        if (edge.Style is not PolylineEdgeStyle) {
          continue;
        }
        var newStyle = (PolylineEdgeStyle) edge.Style.Clone();
        newStyle.Pen = (Pen) NewPen(newStyle.Pen, thickness).GetAsFrozen();
        Graph.SetStyle(edge, newStyle);
      }
    }

    private void ResetEdgeThickness(object sender, RoutedEventArgs e) {
      ResetEdgeThickness();
      UpdateModifiedGraphSample();
    }

    private void ResetEdgeThickness() {
      foreach (var edge in Graph.Edges) {
        if (edge.Style is not PolylineEdgeStyle) {
          continue;
        }
        var newStyle = (PolylineEdgeStyle) edge.Style.Clone();
        newStyle.Pen = (Pen) NewPen(newStyle.Pen, 1).GetAsFrozen();
        Graph.SetStyle(edge, newStyle);
      }
    }

    private static Pen NewPen([CanBeNull] Pen prototype, double thickness) {
      if (prototype == null) {
        return new Pen(Brushes.Black, thickness);
      }
      var newPen = prototype.Clone();
      newPen.Thickness = thickness;
      return newPen;
    }

    private void GenerateRandomEdgeDirectedness(object sender, RoutedEventArgs routedEventArgs) {
      GenerateRandomEdgeDirectednessImpl();
      UpdateModifiedGraphSample();
    }

    private void GenerateRandomEdgeDirectednessImpl() {
      var prototype = GetDemoArrow();
      foreach (var edge in Graph.Edges) {
        var directed = random.Next(2) != 0;
        if (edge.Style is not PolylineEdgeStyle) {
          continue;
        }
        var newStyle = (PolylineEdgeStyle) edge.Style.Clone();
        newStyle.TargetArrow = directed ? CreateArrow(newStyle, prototype) : Arrow.None;
        Graph.SetStyle(edge, newStyle);
      }
    }

    private void ResetEdgeDirectedness(object sender, RoutedEventArgs e) {
      ResetEdgeDirectedness(true);
