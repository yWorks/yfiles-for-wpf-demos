    }

    private void ResetEdgeDirectedness(bool directed = false) {
      var prototype = GetDemoArrow();
      foreach (var edge in Graph.Edges) {
        if (edge.Style is not PolylineEdgeStyle style) {
          continue;
        }
        var createArrow = directed || !style.TargetArrow.Equals(Arrow.None);
        style.TargetArrow = createArrow ? CreateArrow(style, prototype) : Arrow.None;
      }
      Graph.InvalidateDisplays();
    }

    private static Arrow GetDemoArrow() {
      var demoArrow =
          DemoStyles.CreateDemoEdgeStyle(showTargetArrow: true, orthogonalEditing: true).TargetArrow as Arrow;
      return demoArrow ?? Arrow.None;
    }

    private static IArrow CreateArrow(PolylineEdgeStyle style, Arrow arrow) =>
        new Arrow(arrow.Type, style.Pen?.Brush, arrow.Pen, arrow.LengthScale, arrow.WidthScale, arrow.CropLength,
            arrow.CropAtPort);

    private void GenerateRandomLabels(List<ILabelOwner> items) {
      const int wordCountMin = 1;
      const int wordCountMax = 3;
      const double labelPercMin = 0.2;
      const double labelPercMax = 0.7;
      var labelCount = random.Next((int) (items.Count * labelPercMin), (int) (items.Count * labelPercMax));

      RemoveLabels(items);

      var itemsToLabel = items.OrderBy(_ => random.Next()).Take(labelCount);

      // add random item labels
      foreach (var item in itemsToLabel) {
        var wordCount = random.Next(wordCountMin, wordCountMax + 1);
        var label = string.Join(" ",
            Enumerable.Range(0, wordCount).Select(_ => LoremIpsum[random.Next(LoremIpsum.Length)]));
        Graph.AddLabel(item, label);
      }
    }

