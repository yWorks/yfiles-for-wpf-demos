    private class LayoutConfigurationData
    {
      public string Name { get; }

      public LayoutConfiguration Configuration { get; }

      public SampleData[] Samples { get; }

      public LayoutConfigurationData(string name, params SampleData[] samples) {
        Name = name;
        Configuration = SampleData.NewDefaultInstance(samples[0].Configuration.GetType());
        Samples = samples;
      }
    }

    private class SampleData
    {
      public string Name { get; }

      public string FileName { get; }

      public LayoutConfiguration Configuration { get; }

      public SampleData(string name, string fileName, LayoutConfiguration configuration) {
        Name = name;
        FileName = fileName;
        Configuration = configuration;
      }

      public void UpdateConfiguration(LayoutConfiguration configuration) {
        var c = Configuration ?? NewDefaultInstance(configuration.GetType());
        foreach (var propertyInfo in c.GetType().GetProperties(BindingFlags.Instance | BindingFlags.Public)) {
          if (propertyInfo.CanRead && propertyInfo.CanWrite) {
            propertyInfo.SetValue(configuration, propertyInfo.GetValue(c, null), null);
          }
        }
      }

      public static LayoutConfiguration NewDefaultInstance(Type type) =>
          (LayoutConfiguration) Activator.CreateInstance(type);
    }
