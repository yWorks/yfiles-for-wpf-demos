namespace Demo.yFiles.Graph.Input.MoveUnselectedNodes
{
  /// <summary>
  ///   Shows how to use and configure the <see cref="GraphEditorInputMode.MoveUnselectedItemsInputMode"/>.
  /// </summary>
  /// <remarks>
  ///   This special move input mode can be used to move nodes without selecting them first.
  /// </remarks>
  public partial class MoveUnselectedNodesWindow
  {
    /// <summary>
    ///   Automatically generated by Visual Studio.
    ///   Wires up the UI components and adds a
    ///   <see cref="GraphControl"/> to the form.
    /// </summary>
    public MoveUnselectedNodesWindow() {
      InitializeComponent();
    }

    /// <summary>
    ///   Initializes the graph and the input mode.
    /// </summary>
    /// <seealso cref="InitializeInputModes"/>
    /// <seealso cref="InitializeGraph"/>
    protected virtual void OnLoaded(object source, EventArgs e) {
      // initialize the graph
      InitializeGraph();

      // initialize the input mode
      InitializeInputModes();

      // set the input modes to match the initial value of the move mode
      OnMoveModeChanged(null, null);

      GraphControl.FitGraphBounds();
    }

    /// <summary>
    ///   Creates and registers the input modes.
    /// </summary>
    protected virtual void InitializeInputModes() {
      var mode = new GraphEditorInputMode();

      // Always add a label to the newly created nodes
      mode.NodeCreator = (context, graph, location, parent) => {
        var node = graph.CreateNode(location);
        graph.AddLabel(node, "Node");
        return node;
      };

      // The original MoveSelectedItemsInputMode is only active when the 'Move Selected Nodes' toggle button is checked
      mode.MoveSelectedItemsInputMode.Enabled = btnClassic.IsChecked.Value;

      // The MoveUnselectedItemsInputMode is enabled per default,
      // but we configure the recognizer to also respect the IsRecognized method
      mode.MoveUnselectedItemsInputMode.BeginRecognizer = mode.MoveUnselectedItemsInputMode.BeginRecognizer.And(IsRecognized);
      mode.MoveUnselectedItemsInputMode.HoverRecognizer = mode.MoveUnselectedItemsInputMode.HoverRecognizer.And(IsRecognized);

      graphControl.InputMode = mode;
    }

    /// <summary>
    ///   A custom <see cref="EventRecognizer"/> to be used as modifier recognizer.
    /// </summary>
    /// <remarks>
    ///   Has to return true if the move input mode is allowed to move a node.
    /// </remarks>
    private bool IsRecognized(object eventSource, EventArgs eventArg) {
      // return the value according to the Mode combo box
      switch (cmbMode.SelectedIndex) {
        case 0: // always
        case 2: // on top (this is handled by custom IHitTestable)
          // the same as the unmodified MoveUnselectedInputMode;
          return true;
        case 1: // shift is not pressed
          return !EventRecognizers.ShiftIsDown(eventSource, eventArg);
        case 3: // if enabled
          return btnEnable.IsChecked.Value;
        default:
          return false;
      }
    }

    /// <summary>
    ///   Initializes the graph instance setting default styles
    ///   and creating a small sample graph.
    /// </summary>
    protected virtual void InitializeGraph() {
      // set the default node style
      Graph.NodeDefaults.Style = new GroupNodeStyle {
          TabBrush = Themes.PaletteOrange.Fill, ContentAreaPadding = InsetsD.Empty
      };
      Graph.NodeDefaults.Size = new SizeD(60, 80);
      Graph.NodeDefaults.Labels.LayoutParameter = new GroupNodeLabelModel().CreateTabBackgroundParameter();
      Graph.NodeDefaults.Labels.Style = new LabelStyle { TextBrush = Brushes.White };

      Graph.EdgeDefaults.Style = DemoStyles.CreateDemoEdgeStyle();

      // Create a sample node
      Graph.AddLabel(Graph.CreateNode(), "Node");
    }

    /// <summary>
    ///   Returns the GraphControl instance used in the form.
    /// </summary>
    public GraphControl GraphControl => graphControl;

    /// <summary>
    ///   Gets the currently registered IGraph instance from the GraphControl.
    /// </summary>
    public IGraph Graph => GraphControl.Graph;


    private void OnClassicClicked(object sender, RoutedEventArgs e) {
      ((GraphEditorInputMode) graphControl.InputMode).MoveSelectedItemsInputMode.Enabled = btnClassic.IsChecked.Value;
    }

    private void OnEdgeCreationModeChanged(object sender, SelectionChangedEventArgs e) {
      if (graphControl == null) {
        return;
      }
      var selectedIndex = edgeCreationModeSelect.SelectedIndex;
      var geim = graphControl.InputMode as GraphEditorInputMode;
      if (selectedIndex == 0) {
        geim.MoveUnselectedItemsInputMode.Priority = 41;
        geim.MoveSelectedItemsInputMode.Priority = 40;
        geim.CreateEdgeInputMode.StartOverCandidateOnly = false;
      } else if (selectedIndex == 1) {
        geim.MoveUnselectedItemsInputMode.Priority = 47;
        geim.MoveSelectedItemsInputMode.Priority = 46;
        geim.CreateEdgeInputMode.StartOverCandidateOnly = true;
      }
      if (selectedIndex == 0 || cmbMode.SelectedIndex == 0) {
        geim.CreateEdgeInputMode.ShowPortCandidates = ShowPortCandidates.End;
      } else {
        geim.CreateEdgeInputMode.ShowPortCandidates = ShowPortCandidates.All;
      }
    }

    // Called when the mode combo box has changed:
    // if necessary it changes the hit testable for the move input mode
    private void OnMoveModeChanged(object sender, SelectionChangedEventArgs e) {
      var geim = (GraphEditorInputMode) graphControl?.InputMode;
      if (geim == null) {
        return;
      }
      var moveUnselectedItemsInputMode = geim.MoveUnselectedItemsInputMode;
      if (cmbMode.SelectedIndex == 2) {
        // mode 2 (only top region): set a custom hit testable which detects hits
        // only at the top of the nodes
        moveUnselectedItemsInputMode.HitTestable = new TopPaddingHitTestable(geim);
      } else if (moveUnselectedItemsInputMode.HitTestable is TopPaddingHitTestable) {
        // all other modes: if a TopPaddingHitTestable is the current hit testable
        // restore the original hit testable
        moveUnselectedItemsInputMode.HitTestable = GraphEditorInputMode.MoveUnselectedItemsHitTestable;
      }
      // mode 1 (Shift Not Pressed): disable directional constraints (which is bound to Shift too)
      if (cmbMode.SelectedIndex == 1) {
        geim.CreateEdgeInputMode.DirectionalConstraintRecognizer = EventRecognizers.Never;
      } else {
        geim.CreateEdgeInputMode.DirectionalConstraintRecognizer = EventRecognizers.ShiftIsDown;
      }
      OnEdgeCreationModeChanged(null, null);
    }

    /// <summary>
    ///   An IHitTestable implementation which detects hits only on top padding of a node.
    /// </summary>
    private class TopPaddingHitTestable : IHitTestable
    {
      private readonly GraphEditorInputMode inputMode;

      public TopPaddingHitTestable(GraphEditorInputMode inputMode) {
        this.inputMode = inputMode;
      }

      /// <summary>
      ///   Test whether the given location is a valid hit.
      /// </summary>
      /// <remarks>
      ///   The hit is considered as valid if the location lies inside a node's top padding.
      /// </remarks>
      /// <param name="context">The current input mode context.</param>
      /// <param name="location">The location to test.</param>
      public bool IsHit(IInputModeContext context, PointD location) {
        // Get the current hit tester from the input mode context
        var enumerator = context.Lookup(typeof(IHitTester)) as IHitTester;
        if (enumerator != null) {
          // get an enumerator over all elements at the given location
          var hits = enumerator.EnumerateHits(context, location);
          foreach (var item in hits) {
            // if the element is a node and its lookup returns an IGroupPaddingProvider
            var node = item as INode;
            if (node != null) {
              var paddingProvider = node.Lookup<IGroupPaddingProvider>();
              if (paddingProvider != null) {
                // determine whether the given location lies inside the top padding
                var padding = paddingProvider.GetPadding();
                if (new RectD(node.Layout.X, node.Layout.Y, node.Layout.Width, padding.Top).Contains(location)) {
                  // if so: return true
                  return true;
                }
                // else: continue iteration
              }
            }
          }
        }
        // no hits found: return false
        return false;
      }
    }

    private void OnMoveSelectedNodesBtnClicked(object sender, RoutedEventArgs e) {
      var mode = (graphControl.InputMode as GraphEditorInputMode).MoveSelectedItemsInputMode;
      mode.Enabled = !mode.Enabled;
    }
  }
