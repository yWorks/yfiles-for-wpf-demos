  /// <summary>
  ///   Simple Form that hosts a <see cref="GraphControl"/>
  ///   which demonstrates the power of the <see cref="FoldingManager"/>
  ///   for working with grouped graphs and collapsing/expanding group node
  ///   contents.
  /// </summary>
  /// <remarks>
  ///   This demo supports folding operations, i.e., selected group nodes can be expanded
  ///   using CTRL-ADD, and again be collapsed using CTRL-SUBTRACT.
  ///   Use CTRL-PageDown to enter a group node and CTRL-PageUp to exit the current group node.
  /// </remarks>
  public partial class FoldingWindow
  {
    /// <summary>
    ///   Defines the command that is used by the Window to <see cref="ShowContents">show the contents</see>
    ///   of a group node in a separate window.
    /// </summary>
    public static readonly ICommand ShowContentsCommand =
        new RoutedUICommand("Show Contents", "ShowContents", typeof(FoldingWindow));

    private FoldingManager foldingManager;

    /// <summary>
    ///   Automatically generated by Visual Studio.
    ///   Wires up the UI components and adds a
    ///   <see cref="GraphControl"/> to the form.
    /// </summary>
    public FoldingWindow() {
      InitializeComponent();
    }

    /// <summary>
    ///   Initializes the graph and the input mode.
    /// </summary>
    /// <seealso cref="InitializeInputModes"/>
    /// <seealso cref="InitializeGraph"/>
    private void OnLoaded(object sender, EventArgs routedEventArgs) {
      // initialize the graph
      InitializeGraph();

      // initialize the input mode
      InitializeInputModes();
      graphControl.FitGraphBounds();
    }

    /// <summary>
    ///   Calls <see cref="CreateEditorMode"/> and registers
    ///   the result as the <see cref="CanvasControl.InputMode"/>.
    /// </summary>
    protected virtual void InitializeInputModes() {
      graphControl.InputMode = CreateEditorMode();
    }

    /// <summary>
    ///   Creates the default input mode for the GraphControl,
    ///   a <see cref="GraphEditorInputMode"/>.
    /// </summary>
    /// <returns>a new GraphEditorInputMode instance</returns>
    protected virtual IInputMode CreateEditorMode() {
      return new GraphEditorInputMode();
    }

    /// <summary>
    ///   Initializes the graph instance setting default styles
    ///   and creating a small sample graph.
    /// </summary>
    protected virtual void InitializeGraph() {
      // Create the folding manager
      foldingManager = new FoldingManager();

      foldingManager.FoldingEdgeConverter =
          new TypeBasedMergingConverter(edge => edge.Labels.Count > 0 ? edge.Labels[0].Text : null);

      // initialize it with some default for this demo.
      InitializeFoldingManager();

      // initialize the master graph
      DemoStyles.InitDemoStyles(foldingManager.MasterGraph, foldingEnabled : true);

      // enable undoability on the master graph
      foldingManager.MasterGraph.SetUndoEngineEnabled(true);

      // create a managed view
      var view = foldingManager.CreateFoldingView();
      // create undo units for expand and collapse
      view.EnqueueNavigationalUndoUnits = true;

      // and display it
      graphControl.Graph = view.Graph;

      var graph = foldingManager.MasterGraph;

      // try loading the initial sample graph
      try {
        var s = Environment.CurrentDirectory;
        graphControl.ImportFromGraphML(new FileInfo(s + "\\sample.graphml"));
      } catch (IOException) {
        // create initial sample data in our model
        CreateInitialModelGraph(graph);
      }
    }

    /// <summary>
    ///   Creates the initial graph in the model.
    /// </summary>
    /// <param name="graph">The model graph.</param>
    private void CreateInitialModelGraph(IGraph graph) {
      // create some nodes and groups
      var g0 = graph.CreateGroupNode();
      var g1 = graph.CreateGroupNode(g0);
      var c1 = graph.CreateNode(g0);
      var c2 = graph.CreateNode(g0);
      var c3 = graph.CreateNode(g1);
      var c0 = graph.CreateNode();

      // create some edges
      graph.CreateEdge(c1, c2);
      graph.CreateEdge(c0, g0);
      graph.CreateEdge(c0, c1);
      graph.CreateEdge(c2, c0);
      graph.CreateEdge(c2, c3);
      graph.CreateEdge(g1, c0);
    }

    /// <summary>
    ///   Initializes the folding manager.
    /// </summary>
    private void InitializeFoldingManager() {
      // configure our way of displaying collapsed group nodes
      var folderNodeConverter = new FolderNodeConverter();
      // and another initial size
      folderNodeConverter.FolderNodeDefaults.Size = new MutableSize(40, 40);
      // register the converter
      foldingManager.FolderNodeConverter = folderNodeConverter;

      // configure our way of converting edges to folding edges once they connect to collapsed group nodes
      var foldingEdgeConverter = new FoldingEdgeConverter();
      // we want to indicate dummy source ports using a different style
      foldingEdgeConverter.FoldingEdgeDefaults.SourcePort.Style = new ShapePortStyle {
          Shape = ShapeNodeShape.Ellipse,
          Brush = new SolidColorBrush(Color.FromArgb(127, 0, 255, 0)),
          Pen = null,
          RenderSize = new SizeD(3, 3)
      };
      // and also dummy target ports
      foldingEdgeConverter.FoldingEdgeDefaults.TargetPort.Style = new ShapePortStyle {
          Shape = ShapeNodeShape.Ellipse,
          Brush = new SolidColorBrush(Color.FromArgb(127, 0, 255, 0)),
          Pen = null,
          RenderSize = new SizeD(3, 3)
      };
      // also folding edges should look differently
      foldingEdgeConverter.FoldingEdgeDefaults.Style = new PolylineEdgeStyle { Pen = Pens.Red };
      // finally register the converter
      foldingManager.FoldingEdgeConverter = foldingEdgeConverter;
    }


    /// <summary>
    ///   Gets the currently registered <see cref="IGraph"/> instance from the GraphControl.
    /// </summary>
    public IGraph Graph => graphControl.Graph;

    private void ShowContents(INode localRoot) {
      var window = new Window();
      window.Title = "Contents of " + localRoot;
      // we create a new control
      var groupContentsGraphControl = new GraphControl();

      // now obtain a view for the given node from the manager
      var foldingView = foldingManager.CreateFoldingView(localRoot);
      // instead of switching to the ancestor if the localRoot is removed from the graph,
      // we want to dispose the window, instead.
      foldingView.AutoSwitchToAncestor = false;

      // assign the graph and input mode
      groupContentsGraphControl.Graph = foldingView.Graph;
      groupContentsGraphControl.InputMode = CreateEditorMode();

      // show the window
      window.Content = groupContentsGraphControl;
      window.Width = window.Height = 300;
      window.Owner = this;
      window.Show();

      // and fit the bounds
      window.Dispatcher.BeginInvoke(new Action(() => groupContentsGraphControl.FitGraphBounds()));

      // register a delegate that will dispose the window when the view gets invalid
      foldingView.PropertyChanged += delegate(object sender, PropertyChangedEventArgs e) {
        if (e.PropertyName == "Invalid" && foldingView.Invalid) {
          window.Close();
        }
      };
    }


    /// <summary>
    ///   Helper method for the <see cref="ShowContentsCommand"/> binding.
    /// </summary>
    private void OnShowContentsExecuted(object sender, ExecutedRoutedEventArgs e) {
      if (graphControl == null) {
        e.Handled = false;
        return;
      }
      // get the IFoldingView instance
      var graph = graphControl.Graph.Lookup<IFoldingView>();
      if (graph != null) {
        // find the node to show the contents for
        var node = FindNode(graph, e.Parameter);
        // if we found one
        if (node != null) {
          // show it
          ShowContents(graph.GetMasterItem(node));
          e.Handled = true;
        }
      } else {
        e.Handled = false;
      }
    }


    /// <summary>
    ///   Helper method for the <see cref="ShowContentsCommand"/> binding.
    /// </summary>
    private void OnCanShowContentsExecuted(object sender, CanExecuteRoutedEventArgs e) {
      if (graphControl == null) {
        e.Handled = false;
        return;
      }
      // see if we can execute the command...
      var graph = graphControl.Graph.Lookup<IFoldingView>();
      if (graph != null) {
        var node = FindNode(graph, e.Parameter);
        if (node != null) {
          // yes, we found a node - notify the binding.
          e.CanExecute = true;
          e.Handled = true;
        }
      } else {
        e.Handled = false;
      }
    }

    /// <summary>
    ///   Helper method that identifies the node to show the contents of
    ///   if <see cref="ShowContentsCommand"/> is executed.
    /// </summary>
    /// <remarks>
    ///   This method will use the parameter as the return value or the currently selected node
    ///   if it's a group node.
    /// </remarks>
    private INode FindNode(IFoldingView foldingView, object parameter) {
      var node = parameter as INode;
      if (node != null && foldingView.Graph.Contains(node) &&
          !foldingView.Manager.MasterGraph.IsGroupNode(foldingView.GetMasterItem(node))) {
        node = null;
      }
      if (node == null) {
        var selectedNodes = graphControl.Selection.Nodes.GetEnumerator();
        while (selectedNodes.MoveNext()) {
          node = selectedNodes.Current;
          if (foldingView.Graph.Contains(node) &&
              foldingView.Manager.MasterGraph.IsGroupNode(foldingView.GetMasterItem(node))) {
            break;
          }
          node = null;
        }
      }
      return node;
    }

    private void showModelToolStripMenuItem_Click(object sender, EventArgs e) {
      var window = new Window();
      window.Title = "Model";
      var control = new GraphControl();
      // show the master graph
      control.Graph = foldingManager.MasterGraph;
      control.InputMode = CreateEditorMode();

      window.Content = control;
      window.Width = window.Height = 300;
      window.Owner = this;
      window.Show();
      // Remove the graph after closing the window to avoid memory leaks
      window.Closed += (_, _) => control.ClearValue(GraphControl.GraphProperty);

      control.FitGraphBounds();
    }

    private void separateFoldingEdgesToolStripMenuItem_Click(object sender, EventArgs e) {
      // show the view with default settings
      ShowAdditionalManager(new TypeBasedMergingConverter(edge => edge.Labels.Count > 0 ? edge.Labels[0].Text : null));
    }

    private void excludeFoldingEdgesToolStripMenuItem_Click(object sender, EventArgs e) {
      // show the view without folding edges
      ShowAdditionalManager(new ExcludingFoldingEdgeConverter());
    }

    private void mergeFoldingEdgesToolStripMenuItem_Click(object sender, EventArgs e) {
      // show the view with merged folding edges, but consider edges directed
      var mergingFoldingEdgeConverter = new MergingFoldingEdgeConverter();
      mergingFoldingEdgeConverter.IgnoreEdgeDirection = false;

      ShowAdditionalManager(mergingFoldingEdgeConverter);
    }

    private void mergeUndirectedFoldingEdgesToolStripMenuItem_Click(object sender, EventArgs e) {
      // show the view with merged folding edges
      var mergingFoldingEdgeConverter = new MergingFoldingEdgeConverter();
      mergingFoldingEdgeConverter.IgnoreEdgeDirection = true;

      ShowAdditionalManager(mergingFoldingEdgeConverter);
    }

    /// <summary>
    ///   Helper method that creates a window that displays an alternative view of the
    ///   MasterGraph using a separate FoldingManager and therefore a separate set of
    ///   dummy items.
    /// </summary>
    /// <remarks>
    ///   This allows for using different visualizations of the folding edges and collapsed group nodes.
    /// </remarks>
    /// <param name="foldingEdgeConverter">The edge converter to use</param>
    private void ShowAdditionalManager(IFoldingEdgeConverter foldingEdgeConverter) {
      // create the window
      var window = new Window();
      window.Title = "Separate FoldingManager using " + foldingEdgeConverter;

      // create the GraphControl
      var graphControl = new GraphControl();

      // create a new manager for the same master graph.
      var manager = new FoldingManager(foldingManager.MasterGraph);

      // assign the provided converter
      manager.FoldingEdgeConverter = foldingEdgeConverter;

      // create a view
      var foldingView = manager.CreateFoldingView();

      // make the view disappear once it becomes invalid
      foldingView.AutoSwitchToAncestor = false;
      // set the graph
      graphControl.Graph = foldingView.Graph;
      // and edit mode
      graphControl.InputMode = CreateEditorMode();

      // show the window
      window.Content = graphControl;
      window.Width = window.Height = 300;
      window.Owner = this;
      window.Show();

      // fit the bounds
      graphControl.FitGraphBounds();

      // setup delegate to dispose the window once the view becomes invalid
      foldingView.PropertyChanged += delegate(object _sender, PropertyChangedEventArgs _e) {
        if (_e.PropertyName == "Invalid" && foldingView.Invalid) {
          manager.Dispose();
          window.Close();
        }
      };
    }

    /// <summary>
    ///   Callback action that is triggered when the user exits the application.
    /// </summary>
    protected virtual void exitToolStripMenuItem_Click(object sender, EventArgs e) {
      Application.Current.Shutdown();
    }
  }

  public class TypeBasedMergingConverter : IFoldingEdgeConverter
  {
    private readonly Func<IEdge, object> categoryProvider;
    private static readonly object HiddenCategorySentinel = new();

    /// <summary>
    ///   Gets or sets the defaults to apply to folding edges.
    /// </summary>
    /// <remarks>
    ///   Most of the work of <see cref="InitializeFoldingEdgeState"/> and <see cref="UpdateFoldingEdgeState"/>
    ///   is delegated to this instance when edges are initialized or updated.
    /// </remarks>
    public FoldingEdgeDefaults CategorizedEdgeDefaults { get; set; } = new() {
        InitializeOptions = FoldingSynchronizationOptions.None,
        CopyLabels = false,
        Style = new PolylineEdgeStyle { Pen = Pens.Firebrick },
        SourcePort = { LocationParameter = FreeNodePortLocationModel.Center, CopyLabels = false },
        TargetPort = { LocationParameter = FreeNodePortLocationModel.Center, CopyLabels = false }
    };

    /// <summary>
    ///   Gets or sets the defaults to apply to folding edges.
    /// </summary>
    /// <remarks>
    ///   Most of the work of <see cref="InitializeFoldingEdgeState"/> and <see cref="UpdateFoldingEdgeState"/>
    ///   is delegated to this instance when edges are initialized or updated.
    /// </remarks>
    public FoldingEdgeDefaults UncategorizedEdgeDefaults { get; set; } = new() {
        InitializeOptions = FoldingSynchronizationOptions.Layout,
        CopyLabels = true,
        SourcePort = { InitializeOptions = FoldingSynchronizationOptions.All, CopyLabels = true },
        TargetPort = { InitializeOptions = FoldingSynchronizationOptions.All, CopyLabels = true }
    };


    public bool IgnoreDirection { get; set; }

    public TypeBasedMergingConverter(Func<IEdge, object> categoryProvider) {
      this.categoryProvider = categoryProvider;
    }

    public virtual void AddFoldingEdge(
        IFoldingEdgeConverterContext converterContext,
        IFoldingView foldingView,
        IEdge masterEdge,
        INode source,
        bool sourceIsCollapsed,
        INode target,
        bool targetIsCollapsed) {
      var category = categoryProvider(masterEdge);
      if (category != HiddenCategorySentinel) {
        if (category == null) {
          converterContext.AddAsSeparateEdge();
        } else {
          var existingEdge = converterContext.GetExistingFoldingEdges(IgnoreDirection)
              .FirstOrDefault(edge => Equals(categoryProvider(foldingView.GetMasterItem(edge)), category));
          if (existingEdge == null) {
            converterContext.AddAsSeparateEdge();
          } else {
            converterContext.AddToExistingFoldingEdge(existingEdge);
          }
        }
      }
    }

    public virtual void UpdateFoldingEdgeState(
        FoldingEdgeState state,
        IFoldingView foldingView,
        IEdge foldingEdge,
        IReadOnlyList<IEdge> masterEdges) {
      if (masterEdges.Count > 1 || categoryProvider(masterEdges.First()) != null) {
        // categorized
        CategorizedEdgeDefaults.UpdateState(state, foldingView, foldingEdge, masterEdges);

        var labelText = GetCategoryText(masterEdges);
        if (state.Labels.Count == 0) {
          state.AddLabel(labelText);
        } else {
          state.Labels[0].Text = labelText;
          state.Labels[0].AdjustPreferredSize();
        }
      } else {
        UncategorizedEdgeDefaults.UpdateState(state, foldingView, foldingEdge, masterEdges);
      }
    }

    public void UpdateMasterEdges(FoldingEdgeState state, IFoldingView foldingView, IReadOnlyList<IEdge> masterEdges) {
      if (masterEdges.Count > 1 || categoryProvider(masterEdges.First()) != null) {
        // categorized
        for (var i = 0; i < state.Labels.Count; i++) {
          var masterText = GetMasterText(state.Labels[i].Text);
          if (masterText != null) {
            foreach (var masterEdge in masterEdges) {
              ILabel label;
              if (masterEdge.Labels.Count > i) {
                label = masterEdge.Labels[i];
                foldingView.Manager.MasterGraph.SetLabelText(label, masterText);
              } else {
                foldingView.Manager.MasterGraph.AddLabel(masterEdge, masterText);
              }
            }
          }
        }
      }
    }

    private string GetCategoryText(IReadOnlyList<IEdge> masterEdges) {
      var category = categoryProvider(masterEdges[0]);
      var labelText = category == null ? "No Category" : "Category " + category + " (" + masterEdges.Count + ")";
      return labelText;
    }

    private string GetMasterText(string label) {
      if (label == "No Category" || !label.StartsWith("Category ")) {
        return null;
      }
      var masterLabel = label.Substring("Category ".Length);
      if (masterLabel.IndexOf(' ') > 0) {
        masterLabel = masterLabel.Substring(0, masterLabel.IndexOf(' '));
      }
      return masterLabel;
    }

    public virtual void InitializeFoldingEdgeState(
        FoldingEdgeState state,
        IFoldingView foldingView,
        IEdge foldingEdge,
        IReadOnlyList<IEdge> masterEdges) {
      if (masterEdges.Count > 1 || categoryProvider(masterEdges.First()) != null) {
        // categorized
        CategorizedEdgeDefaults.InitializeState(state, masterEdges);

        var labelText = GetCategoryText(masterEdges);
        state.AddLabel(labelText, CategorizedEdgeDefaults.Labels.LayoutParameter, CategorizedEdgeDefaults.Labels.Style);
      } else {
        UncategorizedEdgeDefaults.InitializeState(state, masterEdges);
      }
    }
  }
