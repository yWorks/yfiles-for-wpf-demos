using System;
using System.IO;
using System.Text;
using System.Windows;
using yWorks.Controls;
using yWorks.Graph;
using yWorks.GraphML;

namespace yWorks.Demo.SimpleGraphML
{
  /// <summary>
  ///   Demo that shows how to load and save a
  ///   graph in the XML-based format GraphML using an instance
  ///   of <see cref="GraphMLIOHandler"/>
  /// </summary>
  [Demo("graphml", "view", "GraphML", Summary = "Provides a live view of the graph's GraphML representation.",
      Tags = ["graphml", "i/o"],
      Keywords = ["load", "save", "io", "data panel", "groups", "folding", "labels", "curves", "bezier"])]
  public partial class SimpleGraphMLDemo
  {
    #region GraphML Demo Code

    private GraphMLSupport graphMLSupport = null!;

    /// <summary>
    ///   Automatically generated by Visual Studio.
    ///   Wires up the UI components and adds a
    ///   <see cref="GraphControl"/> to the form.
    /// </summary>
    public SimpleGraphMLDemo() {
      InitializeComponent();
    }

    /// <summary>
    ///   Interpret the text content of the text field as graphml
    /// </summary>
    /// <param name="sender"></param>
    /// <param name="e"></param>
    private void ApplyGraphMLButton_Click(object sender, EventArgs e) {
      try {
        using (var reader = new StringReader(graphMLText.Text)) {
          graphMLSupport.ImportFromGraphML(reader);
        }
      } catch (Exception exc) {
        var exceptionDialog = new ExceptionDialog(exc) { Owner = Window.GetWindow(this) };
        exceptionDialog.ShowDialog();
      }
    }

    private void ShowGraphMLButton_Click(object sender, EventArgs e) {
      ShowGraphML();
    }

    private void ShowGraphML() {
      var includeGraphSettings = IncludeGraphSettingsButton.IsChecked ?? false;
      try {
        var builder = new StringBuilder();
        using (var writer = new StringWriter(builder)) {
          // set whether to make the handler write the graph settings.
          var graphMLIOHandler = graphMLSupport.GraphMLIOHandler;
          graphMLIOHandler.SerializationPropertyOverrides.Set(SerializationProperties.DisableGraphSettings,
              !includeGraphSettings);
          graphMLIOHandler.Write(Graph, writer);
          // Use SelectAll and Paste to enable undoability
          graphMLText.SelectAll();
          graphMLText.Text = builder.ToString();
        }
      } catch (Exception exc) {
        var exceptionDialog = new ExceptionDialog(exc) { Owner = Window.GetWindow(this) };
        exceptionDialog.ShowDialog();
      }
    }

    #endregion GraphML Demo Code

    /// <summary>
    ///   Called just before showing the demo.
    ///   This method initializes the graph and the input mode.
    /// </summary>
    /// <seealso cref="InitializeGraph"/>
    protected override void Initialize() {
      InitializeGraphML();
      // initialize the graph
      InitializeGraph();
      ShowGraphML();
    }

    /// <summary>
    ///   Initializes the graph instance setting default styles
    ///   and creating a small sample graph.
    /// </summary>
    protected virtual void InitializeGraph() {
      DemoStyles.InitDemoStyles(Graph);

      Graph.SetUndoEngineEnabled(true);

      // Read initial graph from embedded resource
      var resource = LoadAssemblyResource("styles.graphml");
      graphMLSupport.ImportFromGraphML(resource);
    }

    /// <summary>
    ///   Initializes the GraphML support and registers command bindings for Open/Save.
    /// </summary>
    private void InitializeGraphML() {
      graphMLSupport = new GraphMLSupport(graphControl);
      graphMLSupport.RegisterOpenSaveCommandBindings();
    }

    #region Standard Demo Actions

    /// <summary>
    ///   Returns the GraphControl instance used in the form.
    /// </summary>
    public GraphControl GraphControl => graphControl;

    /// <summary>
    ///   Gets the currently registered <see cref="IGraph"/> instance from the GraphControl.
    /// </summary>
    public IGraph Graph => GraphControl.Graph;

    /// <summary>
    ///   Gets the currently registered <see cref="IGraphSelection"/> instance from the GraphControl.
    /// </summary>
    public IGraphSelection Selection => GraphControl.Selection;

    #endregion

    [STAThread]
    private static void Main() => Run<SimpleGraphMLDemo>();
  }
}
