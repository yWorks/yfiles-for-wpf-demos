using System.Windows;
using System.Windows.Controls;
using System.Windows.Controls.Primitives;
using System.Windows.Media;
using Demo.yFiles.Toolkit;
using yWorks.Controls;
using yWorks.Controls.Input;
using yWorks.Geometry;
using yWorks.Graph;
using yWorks.Graph.Styles;

namespace Demo.yFiles.Graph.SelectionStyling
{
  /// <summary>
  ///   Demonstrates customized selection rendering of nodes, edges, and labels by decorating these items with a
  ///   corresponding
  ///   style.
  /// </summary>
  public partial class SelectionStylingDemo
  {
    private NodeStyleIndicatorRenderer selectionNodeStyle;
    private bool useCustomNodeSelectionIndicator = true;
    private EdgeStyleIndicatorRenderer selectionEdgeStyle;
    private bool useCustomEdgeSelectionIndicator = true;
    private LabelStyleIndicatorRenderer selectionLabelStyle;
    private bool useCustomLabelSelectionIndicator = true;

    /// <summary>
    ///   Automatically generated by Visual Studio.
    ///   Wires up the UI components and adds a
    ///   <see cref="GraphControl"/> to the form.
    /// </summary>
    public SelectionStylingDemo() {
      InitializeComponent();
    }

    /// <summary>
    ///   Called upon loading of the form.
    ///   This method initializes the graph and the input mode.
    /// </summary>
    protected virtual void OnLoaded(object src, RoutedEventArgs e) {
      // initialize default graph styles
      var graph = graphControl.Graph;
      DemoStyles.InitDemoStyles(graph);

      // initialize the graph
      graphControl.ImportFromGraphML("Resources\\SelectionStyling.graphml");

      // initialize the input mode to enable editing
      graphControl.InputMode = new GraphEditorInputMode {
        // and selecting nodes, edges, and labels at once with the marquee
        MarqueeSelectableItems = GraphItemTypes.LabelOwner | GraphItemTypes.Label
      };

      InitializeDecoration();
      UpdateZoomModeDecoration();

      SelectAllNodes();
      SelectAllEdges();
      SelectAllLabels();
    }

    private void InitializeDecoration() {
      selectionNodeStyle = new NodeStyleIndicatorRenderer {
        NodeStyle = new ShapeNodeStyle {
          Shape = ShapeNodeShape.Rectangle,
          Pen = Pens.DeepSkyBlue,
          Brush = Brushes.Transparent
        },
        Margins = new InsetsD(10)
      };
      selectionEdgeStyle = new EdgeStyleIndicatorRenderer {
        EdgeStyle = new PolylineEdgeStyle { Pen = new Pen(Brushes.DeepSkyBlue, 3) }
      };
      selectionLabelStyle = new LabelStyleIndicatorRenderer {
        LabelStyle =
              new NodeStyleLabelStyleAdapter(
                  new ShapeNodeStyle {
                    Shape = ShapeNodeShape.RoundRectangle,
                    Pen = Pens.DeepSkyBlue,
                    Brush = Brushes.Transparent
                  }, VoidLabelStyle.Instance),
        Margins = new InsetsD(5)
      };

      ZoomModeComboBox.ItemsSource = new[] {
          StyleIndicatorZoomPolicy.Mixed, StyleIndicatorZoomPolicy.NoDownscaling,
          StyleIndicatorZoomPolicy.WorldCoordinates, StyleIndicatorZoomPolicy.ViewCoordinates
      };
      ZoomModeComboBox.SelectedIndex = 0;

      var decorator = graphControl.Graph.GetDecorator();
      decorator.Nodes.SelectionRenderer.AddWrapperFactory((_, original) =>
          useCustomNodeSelectionIndicator ? selectionNodeStyle : original);
      decorator.Edges.SelectionRenderer.AddWrapperFactory((_, original) =>
          useCustomEdgeSelectionIndicator ? selectionEdgeStyle : original);
      decorator.Labels.SelectionRenderer.AddWrapperFactory((_, original) =>
          useCustomLabelSelectionIndicator ? selectionLabelStyle : original);
    }

    /// <summary>
    ///   Sets, removes, and updates the custom selection decoration for nodes,
    ///   edges, and labels according to the current settings.
    /// </summary>
    public void UpdateZoomModeDecoration() {
      var selectedZoomMode = (StyleIndicatorZoomPolicy) ZoomModeComboBox.SelectedItem;
      selectionNodeStyle.ZoomPolicy = selectedZoomMode;
      selectionEdgeStyle.ZoomPolicy = selectedZoomMode;
      selectionLabelStyle.ZoomPolicy = selectedZoomMode;
    }

    private static bool IsChecked(object sender) {
      return ((ToggleButton) sender).IsChecked == true;
    }

    private void SelectAllNodes() {
      var nodeSelection = graphControl.Selection.Nodes;
      nodeSelection.Clear();
      foreach (var node in graphControl.Graph.Nodes) {
        nodeSelection.Add(node);
      }
    }

    private void SelectAllEdges() {
      var edgeSelection = graphControl.Selection.Edges;
      edgeSelection.Clear();
      foreach (var edge in graphControl.Graph.Edges) {
        edgeSelection.Add(edge);
      }
    }

    private void SelectAllLabels() {
      var labelSelection = graphControl.Selection.Labels;
      labelSelection.Clear();
      foreach (var label in graphControl.Graph.Labels) {
        labelSelection.Add(label);
      }
    }

    #region UI event handler

    private void CustomNodeDecorationChanged(object sender, RoutedEventArgs e) {
      useCustomNodeSelectionIndicator = IsChecked(sender);
      SelectAllNodes();
    }

    private void CustomEdgeDecorationChanged(object sender, RoutedEventArgs e) {
      useCustomEdgeSelectionIndicator = IsChecked(sender);
      SelectAllEdges();
    }

    private void CustomLabelDecorationChanged(object sender, RoutedEventArgs e) {
      useCustomLabelSelectionIndicator = IsChecked(sender);
      SelectAllLabels();
    }

    private void ZoomModeChanged(object sender, SelectionChangedEventArgs e) {
      UpdateZoomModeDecoration();
      graphControl.Invalidate();
    }

    #endregion
  }
}
